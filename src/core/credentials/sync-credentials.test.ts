import { describe, expect, test } from 'vitest';
import { fakeWorkflowFileUsing } from '#src/core/compile/credential.fake';
import { WorkflowFile } from '#src/core/compile/workflow.model';
import { fakeCredentialsWriter } from '#src/core/credentials/credentials.fake';
import { knownCredentialTypes, syncCredentials } from '#src/core/credentials/sync-credentials';
import { fakeCredential, fakeN8n, httpError, unreachable } from '#src/core/n8n/n8n.fake';
import { N8nCredential } from '#src/core/n8n/n8n.model';
import { FakeCredentialsWriter } from '#src/core/credentials/credentials.fake';
import { SyncReport } from '#src/core/credentials/credentials.model';
import { FakeN8n } from '#src/core/n8n/n8n.fake';

const FILE = 'credentials/dev.ts';
const LIST_CALL = 'GET /api/v1/credentials';

interface SyncOptions {
  credentials?: N8nCredential[];
  files?: WorkflowFile[];
  knownTypes?: Map<string, string>;
  n8n?: FakeN8n;
}

/** Syncs the target `dev` from an instance holding `credentials`, with the workflow files `files`. */
async function sync({
  credentials = [],
  files = [],
  knownTypes = new Map(),
  n8n = fakeN8n({ credentials }),
}: SyncOptions = {}): Promise<{ report: SyncReport; writer: FakeCredentialsWriter; n8n: FakeN8n }> {
  const writer = fakeCredentialsWriter();
  const report = await syncCredentials({ target: 'dev', client: n8n.client, files, knownTypes }, writer.write);
  return { report, writer, n8n };
}

describe('syncCredentials', () => {
  test('Should write each credential with its key, name, type and id, sorted by key, when the instance has credentials', async () => {
    const { report } = await sync({
      credentials: [fakeCredential('Slack', { id: '2', type: 'slackApi' }), fakeCredential('Gmail sales', { id: '1', type: 'gmailOAuth2' })],
    });

    expect(report).toEqual({
      status: 'synced',
      file: FILE,
      credentials: [
        { key: 'gmail-sales', name: 'Gmail sales', type: 'gmailOAuth2', id: '1' },
        { key: 'slack', name: 'Slack', type: 'slackApi', id: '2' },
      ],
      missing: [],
      exitCode: 0,
    });
  });

  test('Should write a typed file that registers the list and adds the target to CredentialLists when it syncs', async () => {
    const { writer } = await sync({ credentials: [fakeCredential('Gmail sales', { id: '1', type: 'gmailOAuth2' })] });

    expect(writer.text(FILE)).toBe(`// Generated by \`lift creds sync\` from the n8n instance of target "dev". Do not edit: run it again.
// It holds no secret: only the key, name, type and n8n id of each credential. Commit it with the project.
import { defineCredentials } from 'boilerlift';

export const credentials = defineCredentials([
  { key: "gmail-sales", name: "Gmail sales", type: "gmailOAuth2", id: "1" },
]);

export default credentials;

declare module 'boilerlift' {
  interface CredentialLists {
    "dev": typeof credentials;
  }
}
`);
  });

  test('Should write the same text when the instance lists the same credentials in another order', async () => {
    const a = fakeCredential('A', { id: '1' });
    const b = fakeCredential('B', { id: '2' });
    const first = await sync({ credentials: [a, b] });

    const second = await sync({ credentials: [b, a] });

    expect(second.writer.text(FILE)).toBe(first.writer.text(FILE));
  });

  test('Should give the slug of the name in kebab-case, without accents, when the name has spaces, case and accents', async () => {
    const { report } = await sync({ credentials: [fakeCredential('  Gmail – Équipe SALES!  ')] });

    expect(report).toMatchObject({ credentials: [{ key: 'gmail-equipe-sales' }] });
  });

  test('Should append -2 and -3 in the order of the n8n ids when three names give the same key', async () => {
    const { report } = await sync({
      credentials: [fakeCredential('Gmail', { id: 'c' }), fakeCredential('gmail', { id: 'a' }), fakeCredential('GMAIL', { id: 'b' })],
    });

    expect(report).toMatchObject({
      credentials: [
        { key: 'gmail', id: 'a' },
        { key: 'gmail-2', id: 'b' },
        { key: 'gmail-3', id: 'c' },
      ],
    });
  });

  test('Should skip a suffix when another name already gives that key', async () => {
    const { report } = await sync({
      credentials: [fakeCredential('Gmail', { id: 'a' }), fakeCredential('Gmail', { id: 'b' }), fakeCredential('Gmail 2', { id: 'c' })],
    });

    expect(report).toMatchObject({
      credentials: [
        { key: 'gmail', id: 'a' },
        { key: 'gmail-2', id: 'c' },
        { key: 'gmail-3', id: 'b' },
      ],
    });
  });

  test('Should keep the key and record the new id when a credential was recreated with the same name', async () => {
    const { report } = await sync({ credentials: [fakeCredential('Gmail sales', { id: 'new-id' })] });

    expect(report).toMatchObject({ credentials: [{ key: 'gmail-sales', id: 'new-id' }] });
  });

  test('Should report the old key missing with its known type when a used credential was renamed', async () => {
    const { report } = await sync({
      credentials: [fakeCredential('Gmail team', { type: 'gmailOAuth2' })],
      files: [fakeWorkflowFileUsing('workflows/invoice-sync.workflow.ts', ['gmail-sales'], 'unknown')],
      knownTypes: new Map([['gmail-sales', 'gmailOAuth2']]),
    });

    expect(report).toMatchObject({
      credentials: [{ key: 'gmail-team' }],
      missing: [{ key: 'gmail-sales', type: 'gmailOAuth2', workflows: ['invoice-sync'] }],
      exitCode: 8,
    });
  });

  test('Should leave a credential out of the list when the instance no longer has it', async () => {
    const n8n = fakeN8n({ credentials: [fakeCredential('Slack')] });
    n8n.credentials.splice(0);

    const { report } = await sync({ n8n });

    expect(report).toMatchObject({ credentials: [] });
  });

  test('Should report each missing key once, with its workflows sorted, when several workflows use it', async () => {
    const { report } = await sync({
      credentials: [fakeCredential('Slack')],
      files: [
        fakeWorkflowFileUsing('workflows/zeta.json', ['stripe', 'slack', 'stripe']),
        fakeWorkflowFileUsing('workflows/alpha.workflow.ts', ['stripe'], 'stripeApi'),
      ],
    });

    expect(report).toMatchObject({ missing: [{ key: 'stripe', type: 'httpHeaderAuth', workflows: ['alpha', 'zeta'] }], exitCode: 8 });
  });

  test('Should give no type when no list ever held the missing key', async () => {
    const { report } = await sync({ files: [fakeWorkflowFileUsing('workflows/a.json', ['ghost'], 'unknown')] });

    expect(report).toMatchObject({ missing: [{ key: 'ghost', type: undefined }] });
  });

  test('Should write an empty list and exit 0 when the instance has no credentials', async () => {
    const { report, writer } = await sync();

    expect(report).toEqual({ status: 'synced', file: FILE, credentials: [], missing: [], exitCode: 0 });
    expect(writer.text(FILE)).toContain('export const credentials = defineCredentials([]);');
  });

  test('Should exit 8 when the instance has no credentials and workflows use some', async () => {
    const { report } = await sync({ files: [fakeWorkflowFileUsing('workflows/a.json', ['slack'])] });

    expect(report).toMatchObject({ credentials: [], exitCode: 8 });
  });

  test('Should only read the instance when it syncs', async () => {
    const { n8n } = await sync({ credentials: [fakeCredential('Slack')] });

    expect(n8n.calls).toEqual([LIST_CALL]);
  });

  test('Should fail with the missing credential:list scope, exit 9 and write nothing when the instance answers 403', async () => {
    const { report, writer } = await sync({ n8n: fakeN8n({ failures: [httpError(LIST_CALL, 403, 'Forbidden')] }) });

    expect(report).toMatchObject({
      status: 'failed',
      error: { kind: 'scope-missing', call: LIST_CALL, detail: 'HTTP 403: Forbidden: the API key lacks the credential:list scope' },
      exitCode: 9,
    });
    expect(writer.writes).toEqual([]);
  });

  test('Should fail with exit 4, tell to run lift ping and write nothing when the instance rejects the key', async () => {
    const { report, writer } = await sync({ n8n: fakeN8n({ failures: [httpError(LIST_CALL, 401)] }) });

    expect(report).toMatchObject({ status: 'failed', error: { kind: 'key-rejected' }, exitCode: 4 });
    expect(report.status === 'failed' ? report.error.hint : '').toContain('Run lift ping');
    expect(writer.writes).toEqual([]);
  });

  test('Should fail with exit 3, tell to run lift ping and write nothing when the instance is unreachable', async () => {
    const { report, writer } = await sync({ n8n: fakeN8n({ failures: [unreachable(LIST_CALL, 'connection refused')] }) });

    expect(report).toMatchObject({
      status: 'failed',
      error: { kind: 'unreachable', detail: 'unreachable: connection refused' },
      exitCode: 3,
    });
    expect(report.status === 'failed' ? report.error.hint : '').toContain('Run lift ping');
    expect(writer.writes).toEqual([]);
  });

  test('Should fail with exit 10 and the reason when the file cannot be written', async () => {
    const writer = fakeCredentialsWriter({ failWith: 'EACCES: permission denied' });

    const report = await syncCredentials({ target: 'dev', client: fakeN8n().client, files: [], knownTypes: new Map() }, writer.write);

    expect(report).toMatchObject({ status: 'failed', error: { kind: 'write-failed', path: FILE, detail: 'EACCES: permission denied' }, exitCode: 10 });
  });
});

describe('knownCredentialTypes', () => {
  test('Should map each key to its type, the first list winning, when lists hold entries', () => {
    const files = [
      { path: 'credentials/dev.ts', content: [{ key: 'slack', name: 'Slack', type: 'slackApi', id: '1' }] },
      { path: 'credentials/prod.ts', content: [{ key: 'slack', name: 'Slack', type: 'other', id: '2' }] },
      { path: 'credentials/broken.ts', error: 'SyntaxError' },
    ];

    const types = knownCredentialTypes(files);

    expect(types).toEqual(new Map([['slack', 'slackApi']]));
  });
});
